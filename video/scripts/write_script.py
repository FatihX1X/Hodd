#!/usr/bin/env python3
"""Writes demo/SCRIPT.md (the timed subtitle script) and demo/hodd-demo.srt from src/demo/captions.json.

    python3 scripts/write_script.py     # run after scripts/pace_captions.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
caps = json.loads((ROOT / "src/demo/captions.json").read_text())
TITLES = {
    "hook": "00:00–00:12 · Hook",
    "dashboard": "00:12–00:29 · Live treasury",
    "mandate": "00:29–00:54 · Agent wallet, funding and limits",
    "decision": "00:54–01:25 · AI advisor decision and policy",
    "execution": "01:25–01:45 · Execution and Arcscan receipt",
    "usyc": "01:45–02:02 · USYC pool and liquidity",
    "ecosystem": "02:02–02:12 · Hoddie, Claude MCP, Circle Gateway",
    "outro": "02:12–02:20 · Outro",
}


def clock(s):
    return f"{int(s // 60):02d}:{s % 60:05.2f}"


def srt(s):
    ms = int(round(s * 1000))
    return f"{ms // 3_600_000:02d}:{ms // 60_000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


out = [
    "# Hodd demo · subtitle script",
    "",
    "The film has no voiceover: it is told in burned-in English subtitles over an original score.",
    "Timecodes are when each subtitle is on screen. Every claim is traced in [EVIDENCE.md](./EVIDENCE.md).",
    "The source of truth is `demo/subtitles.json`; this file is generated by `scripts/write_script.py`.",
]
segment = None
for c in caps:
    if c["segment"] != segment:
        segment = c["segment"]
        out += ["", f"## {TITLES[segment]}", ""]
    if segment == "outro":
        out.append(f"- `{clock(c['start'])}`  {c['text']}  *(on screen as the closing title, not as a subtitle)*")
    else:
        out.append(f"- `{clock(c['start'])} → {clock(c['end'])}`  {c['text']}")
out += ["", "## Subtitle file", "", "`hodd-demo.srt` holds the same subtitles that are burned into the film."]
(ROOT / "demo/SCRIPT.md").write_text("\n".join(out) + "\n")

shown = [c for c in caps if c["segment"] != "outro"]
cues = []
for i, c in enumerate(shown, 1):
    cues += [str(i), f"{srt(c['start'])} --> {srt(c['end'] + 0.2)}", c["text"], ""]
(ROOT / "demo/hodd-demo.srt").write_text("\n".join(cues))
print(len(shown), "subtitles")
